// Two sources of state brackets, selectable per call:
//   'statutory' (default): the statutory rate schedules and standard deductions in the Tax
//     Foundation workbook, plus the documented corrections in state-corrections.ts.
//   'nfc': the USDA National Finance Center withholding bulletins in data/state-tax/. These are
//     payroll withholding formulas, which can differ from the statute by design (cushion rates,
//     default allowances).
export type StateTaxSource = 'statutory' | 'nfc'
export const DEFAULT_STATE_TAX_SOURCE: StateTaxSource = 'statutory'

export const STATE_TAX_SOURCES: Record<StateTaxSource, string> = {
  statutory:
    'Tax Foundation state income tax rates and brackets, 2026 (reference/income-tax-brackets/2026-State-Individual-Income-Tax-Rate-Brackets.xlsx) with documented corrections',
  nfc: 'USDA National Finance Center state withholding bulletins (data/state-tax/)',
}
export const STATE_TAX_SOURCE = STATE_TAX_SOURCES.statutory
export const STATE_TAX_AS_OF_DATE = '2026'

// ---------------------------------------------------------------------------
// Internal types
// ---------------------------------------------------------------------------

type BracketRow = { floor: number; rate: number }

type StateBracketSchedule = {
  single: BracketRow[]
  married_filing_jointly: BracketRow[]
  single_standard_deduction: number | null
  mfj_standard_deduction: number | null
}

type NfcEntry = StateBracketSchedule & {
  source_md: string
  nfc_reference: string
  as_of_date: string
}

