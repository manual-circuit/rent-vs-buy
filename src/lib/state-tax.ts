// Set of all canonical names for fast lookup
const CANONICAL_NAMES = new Set(Object.keys(STATE_ABBREV_MAP))

// Build abbreviation → canonical reverse map (lower-cased for case-insensitive lookup)
const ABBREV_LOWER_TO_CANONICAL = new Map<string, string>()
for (const [canonical, abbrev] of Object.entries(STATE_ABBREV_MAP)) {
  ABBREV_LOWER_TO_CANONICAL.set(abbrev.toLowerCase(), canonical)
}

// D.C. variants (case-insensitive keys → canonical)
const DC_VARIANTS = new Map<string, string>([
  ['dc', 'D.C.'],
  ['d.c.', 'D.C.'],
  ['washington dc', 'D.C.'],
  ['washington d.c.', 'D.C.'],
  ['district of columbia', 'D.C.'],
])

// ---------------------------------------------------------------------------
// Bracket schedules
// ---------------------------------------------------------------------------
//
// Statutory: src/lib/state-brackets.json is generated by scripts/parse-state-brackets.ts from the
// Tax Foundation workbook. The workbook was compiled in early 2026 and has a few errors, so the
// entries in state-corrections.ts are applied on top; each names the state or NFC publication
// it was checked against.
//
// NFC: src/lib/state-brackets-nfc.json is generated by scripts/build-nfc-brackets.ts from
// src/lib/nfc-state-specs.ts, a hand transcription of the bulletins in data/state-tax/. It
// carries the modeling choices documented at the top of that file (single and joint filers,
// deductions but no credits, no dependents). Each entry records its source bulletin, the NFC
// reference number and the bulletin's published date.
//
// estimateStateIncomeTax runs synchronously in the browser, so both are read at build time.

const NO_TAX_STATES = new Set([
  'Alaska',
  'Florida',
  'Nevada',
  'New Hampshire',
  'South Dakota',
  'Tennessee',
  'Texas',
  'Washington',
  'Wyoming',
])

const statutoryCache = new Map<string, StateBracketSchedule>()
for (const [state, raw] of Object.entries(RAW_BRACKETS as Record<string, RawStateEntry>)) {
  const correction = STATE_CORRECTIONS[state]
  statutoryCache.set(state, correction ? applyCorrection(raw, correction) : raw)
}

const nfcCache = new Map<string, NfcEntry>(
  Object.entries(RAW_NFC_BRACKETS as Record<string, NfcEntry>),
)

