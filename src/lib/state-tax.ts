// Set of all canonical names for fast lookup
const CANONICAL_NAMES = new Set(Object.keys(STATE_ABBREV_MAP))

// Build abbreviation → canonical reverse map (lower-cased for case-insensitive lookup)
const ABBREV_LOWER_TO_CANONICAL = new Map<string, string>()
for (const [canonical, abbrev] of Object.entries(STATE_ABBREV_MAP)) {
  ABBREV_LOWER_TO_CANONICAL.set(abbrev.toLowerCase(), canonical)
}

// D.C. variants (case-insensitive keys → canonical)
const DC_VARIANTS = new Map<string, string>([
  ['dc', 'D.C.'],
  ['d.c.', 'D.C.'],
  ['washington dc', 'D.C.'],
  ['washington d.c.', 'D.C.'],
  ['district of columbia', 'D.C.'],
])

// ---------------------------------------------------------------------------
// Bracket schedules (generated from the NFC bulletins)
// ---------------------------------------------------------------------------
//
// src/lib/state-brackets-nfc.json is generated by scripts/build-nfc-brackets.ts from
// src/lib/nfc-state-specs.ts, a hand transcription of the USDA National Finance Center
// withholding bulletins in data/state-tax/. estimateStateIncomeTax runs synchronously in the
// browser, so the bulletins are read at build time, never at runtime.
//
// The bulletins are payroll withholding formulas, so each schedule carries the modeling choices
// documented at the top of nfc-state-specs.ts: single and joint filers only, deductions from
// income but no credits, and no dependents. Each entry records its source bulletin (source_md),
// the NFC reference number and the bulletin's published date (as_of_date); some states' bulletins
// are years old, so check as_of_date before treating a schedule as current law.
//
// To refresh: run scripts/nfc_tax_refs.py (or merge the scheduled refresh PR), then update any
// spec that `pnpm test` flags, run `node scripts/build-nfc-brackets.ts`, and commit.

const NO_TAX_STATES = new Set([
  'Alaska',
  'Florida',
  'Nevada',
  'New Hampshire',
  'South Dakota',
  'Tennessee',
  'Texas',
  'Washington',
  'Wyoming',
])

const bracketCache = new Map<string, StateBracketSchedule>(
  Object.entries(RAW_NFC_BRACKETS as Record<string, StateBracketSchedule>),
)

// ---------------------------------------------------------------------------
// Exports
// ---------------------------------------------------------------------------

/**
 * Returns the canonical state name for the given input string, or null if not recognized.
 * Accepts canonical names, abbreviations, and common D.C. variants.
 * Case-insensitive.
 */
export function normalizeStateName(input: string): string | null {
  const lower = input.trim().toLowerCase()

  // D.C. special cases first (some overlap with 'washington')
  const dcMatch = DC_VARIANTS.get(lower)
  if (dcMatch) return dcMatch

  // Canonical name pass-through (case-insensitive)
  for (const canonical of CANONICAL_NAMES) {
    if (canonical.toLowerCase() === lower) return canonical
  }

  // Abbreviation reverse lookup
  const fromAbbrev = ABBREV_LOWER_TO_CANONICAL.get(lower)
  if (fromAbbrev) return fromAbbrev

  return null
}

/**
 * Returns true if the state has no income tax on wages (always returns 0).
 * Returns false for unrecognized state names.
 */
export function isNoTaxState(state: string): boolean {
  const canonical = normalizeStateName(state)
  if (!canonical) return false
  return NO_TAX_STATES.has(canonical)
}

/**
 * Where a state's schedule came from: the NFC bulletin file, its reference number and its
 * published date. Null for no-income-tax states and unrecognized names.
 */
export function stateTaxProvenance(
  state: string,
): { source_md: string; nfc_reference: string; as_of_date: string } | null {
  const canonical = normalizeStateName(state)
  const schedule = canonical ? bracketCache.get(canonical) : undefined
  if (!schedule) return null
  return {
    source_md: schedule.source_md,
    nfc_reference: schedule.nfc_reference,
    as_of_date: schedule.as_of_date,
  }
}

/**
 * Estimates annual state income tax for the given state, gross income, and filing status.
 *
 * Filing status is limited to 'single' and 'married_filing_jointly'; callers must map
 * 'married_filing_separately' and 'head_of_household' to 'single' before calling.
 *
 * Returns 0 for:
 * - grossIncome <= 0
 * - unrecognized state name
 * - no-income-tax states (Alaska, Florida, Nevada, South Dakota, Tennessee,
 *   Texas, Washington, Wyoming, New Hampshire)
 */
export function estimateStateIncomeTax(
  state: string,
  grossIncome: number,
  filingStatus: 'single' | 'married_filing_jointly',
): number {
  if (grossIncome <= 0) return 0

  const canonical = normalizeStateName(state)
  if (!canonical) return 0

  if (NO_TAX_STATES.has(canonical)) return 0

  const schedule = bracketCache.get(canonical)
  if (!schedule) return 0

  const brackets =
    filingStatus === 'married_filing_jointly' ? schedule.married_filing_jointly : schedule.single

  const stdDed =
    filingStatus === 'married_filing_jointly'
      ? schedule.mfj_standard_deduction
      : schedule.single_standard_deduction

  const taxableIncome = Math.max(0, grossIncome - stdDed)

  let tax = 0
  for (let i = 0; i < brackets.length; i++) {
    const bracket = brackets[i]
    if (bracket === undefined) break
    const { floor, rate } = bracket
    const next = brackets[i + 1]
    const ceil = next !== undefined ? next.floor : Infinity
    if (taxableIncome <= floor) break
    tax += (Math.min(taxableIncome, ceil) - floor) * rate
  }
  return tax
}
